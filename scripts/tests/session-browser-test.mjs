import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const { chromium } = createRequire(process.env.HYPERION_TEST_TOOLS || import.meta.url)('playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
try {
  const context = await browser.newContext()
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.clock.install({ time: new Date('2026-11-02T00:00:00Z') })
  await page.clock.pauseAt(new Date('2026-11-02T00:00:00Z'))
  const url = process.env.HYPERION_SESSION_TEST_URL || 'http://127.0.0.1:4177/scripts/tests/session-browser.html'
  await page.goto(url)
  await page.evaluate(() => navigator.serviceWorker.ready)
  await page.reload()
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller))
  const timer = page.getByRole('timer', { name: 'Session elapsed time' })
  assert.match(await timer.innerText(), /00:01:05/)
  await page.clock.fastForward(61000)
  assert.match(await timer.innerText(), /00:02:06/)
  await page.getByRole('button', { name: 'Next question' }).click()
  assert.match(await timer.innerText(), /00:02:06/)
  await page.clock.setSystemTime(new Date('2026-11-02T00:03:01Z'))
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')))
  assert.match(await timer.innerText(), /00:04:06/)
  await page.getByRole('button', { name: 'Resume saved session' }).click()
  assert.match(await timer.innerText(), /01:01:01/)
  await page.getByRole('button', { name: 'New session' }).click()
  assert.match(await timer.innerText(), /00:00:00/)
  const bookmark = index => page.getByRole('button', { name: `Bookmark question ${index}`, exact: true })
  const remove = index => page.getByRole('button', { name: `Remove bookmark ${index}`, exact: true })
  await bookmark(1).click()
  assert.equal(await remove(1).getAttribute('aria-pressed'), 'true')
  assert.equal(await bookmark(2).getAttribute('aria-pressed'), 'false')
  await bookmark(2).click()
  await remove(1).click()
  assert.equal(await bookmark(1).getAttribute('aria-pressed'), 'false')
  assert.equal(await remove(2).getAttribute('aria-pressed'), 'true')
  // Drain the real encrypted storage queue before closing/reloading the document.
  await page.waitForFunction(async () => {
    const db = await new Promise(resolve => { const request = indexedDB.open('hyperion-encrypted-browser-state'); request.onsuccess = () => resolve(request.result) })
    const get = (store, key) => new Promise(resolve => { const request = db.transaction(store).objectStore(store).get(key); request.onsuccess = () => resolve(request.result) })
    const entry = await get('entries', 'hyperion-bookmarks')
    const key = await get('keys', 'encrypted-persist-state-key')
    if (!entry || !key) return false
    const bytes = await crypto.subtle.decrypt({ name: 'AES-GCM', iv: entry.iv }, key.key, entry.ciphertext)
    const saved = JSON.parse(JSON.parse(new TextDecoder().decode(bytes)))
    db.close()
    return saved.state.items.length === 1 && saved.state.items[0].id === 'session-test-2'
  }, null, { polling: 'raf' })
  await context.setOffline(true)
  await page.reload()
  await remove(2).waitFor()
  assert.equal(await bookmark(1).getAttribute('aria-pressed'), 'false')
  await page.clock.fastForward(5000)
  assert.match(await timer.innerText(), /00:01:10/)
  assert.deepEqual(errors, [])
  console.log('PASS: elapsed display, question navigation, wake catch-up, resumed/new session, per-question bookmark identity/removal, encrypted persistence and offline reload.')
} finally { await browser.close() }
