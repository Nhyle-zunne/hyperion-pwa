import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || chromium.executablePath(), args: ['--no-sandbox'] })
try {
  for (const mode of ['PRACTICE', 'DRILL', 'MOCK']) {
    const page = await browser.newPage({ viewport: { width: 1531, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    if (mode === 'DRILL') await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.route('**/*', route => ['localhost', '127.0.0.1', '[::1]'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
    await page.goto(`${process.env.HYPERION_RECOVERY_TEST_URL}?mode=${mode}`)
    await page.getByRole('button', { name: 'Finish fixture session', exact: true }).waitFor()
    const started = Date.now()
    await page.evaluate(() => window.resultsFixture.finish())
    const processing = page.getByRole('dialog', { name: 'Processing Results', exact: true })
    await processing.waitFor()
    if (mode === 'DRILL') assert.equal(await processing.locator('.results-processing-spinner').evaluate(element => getComputedStyle(element).animationName), 'none')
    await page.screenshot({ path: `processing-results-${mode.toLowerCase()}.png` })
    await processing.waitFor({ state: 'hidden' })
    assert(Date.now() - started >= 2850, 'Android-style sequence remains readable for three seconds')
    const results = page.getByRole('region', { name: 'Session results' })
    await results.waitFor()
    assert.equal(await page.evaluate(() => window.resultsFixture.state().score.percent), 33)
    assert.equal(await page.evaluate(() => window.resultsFixture.history().length), 1, 'Repeated finish creates one history entry')
    assert.equal(await page.evaluate(async () => (await window.resultsFixture.snapshot()).finished), true, 'Results retain a completed durable audit')
    assert((await results.boundingBox()).width <= 560, 'Results use competence selection width')
    await page.screenshot({ path: `results-${mode.toLowerCase()}-desktop.png`, fullPage: true })
    await page.getByRole('button', { name: 'Review C1 questions', exact: true }).click()
    assert.equal(await page.evaluate(() => document.activeElement.id), 'results-review-tab', 'Competence review keeps keyboard focus on its destination tab')
    await page.keyboard.press('Home')
    await page.getByRole('tab', { name: 'Competence Breakdown', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    assert.equal(await page.getByRole('tab', { name: 'Question Review', exact: false }).getAttribute('aria-selected'), 'true', 'Result tabs support keyboard navigation')
    await results.getByLabel('Competence', { exact: true }).selectOption('all')
    await results.getByText('Synthetic question 3?', { exact: true }).waitFor()
    await results.getByText('Unanswered', { exact: true }).waitFor()
    await results.getByLabel('Competence', { exact: true }).selectOption('C1')
    assert.equal(await results.getByText('Synthetic question 3?', { exact: true }).count(), 0)
    await results.getByLabel('Competence', { exact: true }).selectOption('all')
    await page.getByRole('button', { name: 'Missed only', exact: false }).click()
    assert.equal(await results.getByText('Synthetic question 1?', { exact: true }).count(), 0)
    await results.getByText('Synthetic question 2?', { exact: true }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Review fits mobile without horizontal scrolling')
    await page.screenshot({ path: `results-${mode.toLowerCase()}-mobile.png`, fullPage: true })
    assert.deepEqual(errors, [])
    await page.close()
  }
  const page = await browser.newPage({ viewport: { width: 1531, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => ['localhost', '127.0.0.1', '[::1]'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  const open = async suffix => { await page.goto(process.env.HYPERION_RECOVERY_TEST_URL + suffix); await page.getByRole('button', { name: 'Finish fixture session', exact: true }).waitFor() }
  await open('')
  await page.evaluate(() => {
    const original = crypto.subtle.encrypt.bind(crypto.subtle)
    const gate = new Promise(resolve => { window.releaseResultsWrite = () => { crypto.subtle.encrypt = original; resolve() } })
    crypto.subtle.encrypt = async (...args) => { await gate; return original(...args) }
    window.resultsFixture.finish()
  })
  const processing = page.getByRole('dialog', { name: 'Processing Results', exact: true })
  await processing.waitFor()
  await page.waitForTimeout(3200)
  assert.equal(await processing.isVisible(), true, 'Slow durable write keeps processing visible after the animation')
  assert.equal(await page.evaluate(() => window.resultsFixture.state().finished), false)
  assert.equal(await page.evaluate(() => window.resultsFixture.history().length), 0)
  await page.evaluate(() => window.releaseResultsWrite())
  await processing.waitFor({ state: 'hidden' })
  assert.equal(await page.evaluate(() => window.resultsFixture.history().length), 1)
  await open('')
  await page.evaluate(() => {
    window.originalResultsPut = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function(value, ...args) {
      if (this.name === 'snapshots' && value.finished === true) throw new DOMException('Synthetic storage failure', 'QuotaExceededError')
      return window.originalResultsPut.call(this, value, ...args)
    }
    window.resultsFixture.finish()
  })
  await page.getByRole('alert').waitFor()
  assert.equal(await processing.isVisible(), false, 'Save failure does not trap the retry action behind processing')
  assert.equal(await page.evaluate(() => window.resultsFixture.state().finished), false)
  assert.equal(await page.evaluate(() => window.resultsFixture.state().score.percent), 33, 'Failed save keeps answers intact')
  await page.evaluate(() => { IDBObjectStore.prototype.put = window.originalResultsPut })
  await page.getByRole('button', { name: 'Retry saving completed session', exact: true }).click()
  await processing.waitFor()
  await processing.waitFor({ state: 'hidden' })
  await open('?mode=MOCK&managed=1')
  await page.evaluate(() => window.resultsFixture.finish())
  await processing.waitFor()
  await page.getByText('Fixture destination', { exact: true }).waitFor()
  assert.equal(await processing.isVisible(), true, 'Mock competence route changes preserve the processing sequence')
  await processing.waitFor({ state: 'hidden' })
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('hyperion-mock-exam-plan-v1')).results.C1.percent), 16.67, 'Existing weighted mock score is unchanged')
  await page.evaluate(() => window.resultsFixture.presentOverallMock())
  await processing.waitFor()
  await processing.waitFor({ state: 'hidden' })
  await open('')
  await page.evaluate(() => window.resultsFixture.finish())
  await processing.waitFor()
  await page.evaluate(() => window.resultsFixture.reset())
  await processing.waitFor({ state: 'hidden' })
  assert.deepEqual(errors, [])
  await page.close()
  console.log('PASS: practice/drill/mock processing, unchanged scores, durable completion, review filters and narrow responsive results')
} finally { await browser.close() }
