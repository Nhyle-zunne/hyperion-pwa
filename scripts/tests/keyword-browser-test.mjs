// Requires Playwright and Chromium. HYPERION_TEST_TOOLS may select an external package.json
// containing Playwright; HYPERION_KEYWORD_TEST_URL selects the fixture preview server.
import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const { chromium } = createRequire(process.env.HYPERION_TEST_TOOLS || import.meta.url)('playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
try {
  const context = await browser.newContext()
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const url = process.env.HYPERION_KEYWORD_TEST_URL || 'http://127.0.0.1:4176/scripts/tests/keyword-browser.html'
  await page.goto(url)
  await page.evaluate(() => navigator.serviceWorker.ready)
  await page.reload()
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller))
  const edit = () => page.getByRole('button', { name: 'Edit Keyword', exact: true })
  const save = () => page.getByRole('button', { name: 'Save Keywords', exact: true })
  const word = index => page.locator('#stem').getByRole('button', { name: new RegExp(`^Highlight word ${index}:`) })
  const marks = () => page.locator('#stem mark').allTextContents()
  const ready = async () => {
    await edit().waitFor()
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent?.trim() === 'Edit Keyword' && !button.disabled))
  }
  assert.equal(await edit().count(), 0)
  await page.getByRole('switch', { name: 'Highlight Keywords' }).check()
  await edit().click()
  assert.equal(await page.locator('#stem').getByRole('button', { name: /^Highlight symbol .*: ;$/ }).count(), 1, 'Punctuation must be independently highlightable')
  await word(1).click()
  await word(3).focus()
  await page.keyboard.press('Space')
  await save().click()
  await ready()
  assert.deepEqual(await marks(), ['Vessel', 'way'])
  await page.reload()
  await ready()
  assert.deepEqual(await marks(), ['Vessel', 'way'])
  await context.setOffline(true)
  await page.reload()
  await ready()
  assert.deepEqual(await marks(), ['Vessel', 'way'])
  await edit().click()
  await word(1).click()
  await word(4).click()
  await save().click()
  await ready()
  assert.deepEqual(await marks(), ['way', 'vessel'])
  await page.getByRole('switch', { name: 'Highlight Keywords' }).uncheck()
  assert.equal(await edit().count(), 0)
  assert.deepEqual(await marks(), [])
  await page.reload()
  assert.equal(await page.getByRole('switch').isChecked(), false)
  await page.getByRole('switch').check()
  await ready()
  assert.deepEqual(await marks(), ['way', 'vessel'])
  await edit().click()
  await word(2).click() // Unsaved draft must be discarded.
  await page.getByRole('button', { name: 'Change question', exact: true }).click()
  await ready()
  assert.deepEqual(await marks(), [])
  await page.getByRole('button', { name: 'Change question', exact: true }).click()
  await ready()
  assert.deepEqual(await marks(), ['way', 'vessel'])
  await page.getByRole('button', { name: 'Change track' }).click()
  await ready()
  assert.deepEqual(await marks(), [])
  await page.getByRole('button', { name: 'Change track' }).click()
  await ready()
  assert.deepEqual(await marks(), ['way', 'vessel'])
  // A failed write must keep editing and preserve the previous stored selections.
  await edit().click()
  await word(2).click()
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (value, ...args) {
      if (value?.id?.startsWith('hyperion-keywords:')) throw new DOMException('Test quota', 'QuotaExceededError')
      return original.call(this, value, ...args)
    }
  })
  await save().click()
  await page.getByRole('alert').waitFor()
  assert.match(await page.getByRole('alert').innerText(), /could not be saved/)
  assert.equal(await save().count(), 1)
  await page.reload()
  await ready()
  assert.deepEqual(await marks(), ['way', 'vessel'])
  // Editing a choice never activates its answer, including keyboard input.
  await page.getByRole('switch').check()
  await ready()
  const choice = () => page.locator('.fixture-choice').filter({ hasText: 'Port, not starboard.' })
  await edit().click()
  assert.equal(await choice().evaluate(node => node.tagName), 'DIV')
  assert.equal(await page.locator('.fixture-choice button button').count(), 0)
  await choice().getByRole('button', { name: /^Highlight word 1: Port$/ }).click()
  await choice().getByRole('button', { name: /^Highlight symbol .*: ,$/ }).focus()
  await page.keyboard.press('Space')
  const secondChoice = () => page.locator('.fixture-choice').filter({ hasText: 'Keep clear:' })
  assert.equal(await secondChoice().getByRole('button', { name: /^Highlight symbol .*: _$/ }).count(), 5)
  await secondChoice().getByRole('button', { name: /^Highlight symbol .*: _$/ }).nth(2).click()
  await secondChoice().getByRole('button', { name: /^Highlight symbol .*: '$/ }).click()
  await secondChoice().getByRole('button', { name: /^Highlight word .*: give-way$/ }).first().click()
  await secondChoice().getByRole('button', { name: /^Highlight symbol .*: -$/ }).click()
  assert.equal(await secondChoice().getByRole('button', { name: /^Highlight symbol .*: -$/ }).getAttribute('aria-pressed'), 'false', 'A highlighted compound word must allow its punctuation to be removed independently')
  await secondChoice().getByRole('button', { name: /^Highlight word .*: give-way$/ }).first().click()
  await secondChoice().getByRole('button', { name: /^Highlight symbol .*: -$/ }).click()
  assert.equal(await secondChoice().textContent(), "Keep clear: _____! ship's give-way", 'Token targets must not duplicate or change choice text')
  assert.equal(await page.getByLabel('Selected answer').innerText(), 'No answer')
  await save().click()
  await ready()
  assert.deepEqual(await choice().locator('mark').allTextContents(), ['Port', ','])
  assert.deepEqual(await secondChoice().locator('mark').allTextContents(), ['_', "'", '-'])
  await page.getByRole('button', { name: 'Shuffle choices' }).click()
  assert.deepEqual(await choice().locator('mark').allTextContents(), ['Port', ','])
  await choice().click()
  assert.equal(await page.getByLabel('Selected answer').innerText(), 'Port, not starboard.')
  await page.reload()
  await ready()
  assert.deepEqual(await choice().locator('mark').allTextContents(), ['Port', ','])
  await edit().click()
  await choice().getByRole('button', { name: /^Highlight word 2: not$/ }).click()
  await page.getByRole('switch').uncheck()
  await page.getByRole('switch').check()
  await ready()
  assert.deepEqual(await choice().locator('mark').allTextContents(), ['Port', ','], 'Disabling highlights discards all unsaved choice edits')
  await edit().click()
  await choice().getByRole('button', { name: /^Highlight word 2: not$/ }).click()
  await page.getByRole('button', { name: 'Change question', exact: true }).click()
  await ready()
  assert.deepEqual(await page.locator('.fixture-choice mark').allTextContents(), [])
  await page.getByRole('button', { name: 'Change question', exact: true }).click()
  await ready()
  assert.deepEqual(await choice().locator('mark').allTextContents(), ['Port', ','])
  await edit().click()
  await choice().getByRole('button', { name: /^Highlight word 2: not$/ }).click()
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (value, ...args) {
      if (value?.id?.startsWith('hyperion-keywords:')) throw new DOMException('Test quota', 'QuotaExceededError')
      return original.call(this, value, ...args)
    }
  })
  await save().click()
  await page.getByRole('alert').waitFor()
  assert.equal(await save().count(), 1)
  await page.reload()
  await ready()
  assert.deepEqual(await choice().locator('mark').allTextContents(), ['Port', ','], 'Failed choice save preserves the previous encrypted record')
  await page.getByRole('button', { name: 'Revise choice' }).click()
  await ready()
  assert.deepEqual(await page.locator('.fixture-choice').filter({ hasText: 'Revised choice?' }).locator('mark').allTextContents(), [], 'Changed choice text cannot inherit previous highlights')
  await edit().click()
  await save().click()
  await ready()
  await page.reload()
  await ready()
  assert.deepEqual(await choice().locator('mark').allTextContents(), ['Port', ','], 'Saving revised choices must retain highlights for historical exact choice text')
  await page.getByRole('button', { name: 'Revise question' }).click()
  await ready()
  assert.deepEqual(await marks(), [])
  await context.setOffline(false)
  const legacyContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true })
  const legacyPage = await legacyContext.newPage()
  await legacyPage.goto(url)
  await legacyPage.getByRole('button', { name: 'Seed legacy highlights' }).click()
  await legacyPage.getByText('Legacy highlights seeded', { exact: true }).waitFor()
  await legacyPage.getByRole('switch').check()
  await legacyPage.getByRole('button', { name: 'Edit Keyword', exact: true }).waitFor()
  await legacyPage.waitForFunction(() => document.querySelectorAll('#stem mark').length === 2)
  assert.deepEqual(await legacyPage.locator('#stem mark').allTextContents(), ['Vessel', 'way'])
  await legacyPage.getByRole('button', { name: 'Edit Keyword', exact: true }).click()
  await legacyPage.locator('#stem').getByRole('button', { name: /^Highlight symbol .*: ;$/ }).click()
  await legacyPage.locator('.fixture-choice').first().getByRole('button', { name: /^Highlight word 1: Port$/ }).click()
  await legacyPage.getByRole('button', { name: 'Save Keywords', exact: true }).click()
  await legacyPage.getByRole('button', { name: 'Edit Keyword', exact: true }).waitFor()
  await legacyPage.reload()
  await legacyPage.waitForFunction(() => document.querySelectorAll('#stem mark').length === 3)
  assert.deepEqual(await legacyPage.locator('#stem mark').allTextContents(), ['Vessel', 'way', ';'])
  assert.deepEqual(await legacyPage.locator('.fixture-choice mark').allTextContents(), ['Port'])
  await legacyContext.close()
  assert.deepEqual(errors, [])
  console.log('PASS: multi-word and repeated-word selection, keyboard editing, save/reload, offline startup/save, toggle persistence, draft discard, track/question/revision isolation, save-failure recovery, punctuation, choice persistence/shuffling/revisions, and answer isolation during keyword editing.')
} finally {
  await browser.close()
}
