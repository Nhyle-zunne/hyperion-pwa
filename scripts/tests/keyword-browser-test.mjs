// Requires Playwright and Chromium. HYPERION_TEST_TOOLS may select an external package.json
// containing Playwright; HYPERION_KEYWORD_TEST_URL selects the fixture preview server.
import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const { chromium } = createRequire(process.env.HYPERION_TEST_TOOLS || import.meta.url)('playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
try {
  const context = await browser.newContext()
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const url = process.env.HYPERION_KEYWORD_TEST_URL || 'http://127.0.0.1:4176/scripts/tests/keyword-browser.html'
  await page.goto(url)
  await page.evaluate(() => navigator.serviceWorker.ready)
  await page.reload()
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller))
  const edit = () => page.getByRole('button', { name: 'Edit Keyword', exact: true })
  const save = () => page.getByRole('button', { name: 'Save Keywords', exact: true })
  const word = index => page.getByRole('button', { name: new RegExp(`^Highlight word ${index}:`) })
  const marks = () => page.locator('mark').allTextContents()
  const ready = async () => {
    await edit().waitFor()
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent?.trim() === 'Edit Keyword' && !button.disabled))
  }
  assert.equal(await edit().count(), 0)
  await page.getByRole('switch', { name: 'Highlight Keywords' }).check()
  await edit().click()
  await word(1).click()
  await word(3).focus()
  await page.keyboard.press('Space')
  await save().click()
  await ready()
  assert.deepEqual(await marks(), ['Vessel', 'way'])
  await page.reload()
  await ready()
  assert.deepEqual(await marks(), ['Vessel', 'way'])
  await context.setOffline(true)
  await page.reload()
  await ready()
  assert.deepEqual(await marks(), ['Vessel', 'way'])
  await edit().click()
  await word(1).click()
  await word(4).click()
  await save().click()
  await ready()
  assert.deepEqual(await marks(), ['way', 'vessel'])
  await page.getByRole('switch', { name: 'Highlight Keywords' }).uncheck()
  assert.equal(await edit().count(), 0)
  assert.deepEqual(await marks(), [])
  await page.reload()
  assert.equal(await page.getByRole('switch').isChecked(), false)
  await page.getByRole('switch').check()
  await ready()
  assert.deepEqual(await marks(), ['way', 'vessel'])
  await edit().click()
  await word(2).click() // Unsaved draft must be discarded.
  await page.getByRole('button', { name: 'Change question', exact: true }).click()
  await ready()
  assert.deepEqual(await marks(), [])
  await page.getByRole('button', { name: 'Change question', exact: true }).click()
  await ready()
  assert.deepEqual(await marks(), ['way', 'vessel'])
  await page.getByRole('button', { name: 'Change track' }).click()
  await ready()
  assert.deepEqual(await marks(), [])
  await page.getByRole('button', { name: 'Change track' }).click()
  await ready()
  assert.deepEqual(await marks(), ['way', 'vessel'])
  // A failed write must keep editing and preserve the previous stored selections.
  await edit().click()
  await word(2).click()
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (value, ...args) {
      if (value?.id?.startsWith('hyperion-keywords:')) throw new DOMException('Test quota', 'QuotaExceededError')
      return original.call(this, value, ...args)
    }
  })
  await save().click()
  await page.getByRole('alert').waitFor()
  assert.match(await page.getByRole('alert').innerText(), /could not be saved/)
  assert.equal(await save().count(), 1)
  await page.reload()
  await ready()
  assert.deepEqual(await marks(), ['way', 'vessel'])
  await page.getByRole('button', { name: 'Revise question' }).click()
  await ready()
  assert.deepEqual(await marks(), [])
  await context.setOffline(false)
  assert.deepEqual(errors, [])
  console.log('PASS: multi-word and repeated-word selection, keyboard editing, save/reload, offline startup/save, toggle persistence, draft discard, track/question/revision isolation, and save-failure recovery.')
} finally {
  await browser.close()
}
