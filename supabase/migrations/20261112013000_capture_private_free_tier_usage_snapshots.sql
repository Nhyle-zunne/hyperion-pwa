begin;
set local lock_timeout = '5s';

-- Free/Nano readiness instrumentation; one tiny, private aggregate row per day.
-- This does NOT sample Supabase's host Disk IO Budget balance, IOPS, CPU,
-- memory or egress. Compare those separately in Supabase Observability/Usage.
-- Never store user IDs, question content, payment details or auth credentials.
create schema if not exists hyperion_ops;
revoke all on schema hyperion_ops from public, anon, authenticated, service_role;

create table if not exists hyperion_ops.free_tier_usage_samples (
  sampled_on date primary key,
  measured_at timestamptz not null,
  database_bytes bigint not null,
  storage_bytes bigint not null,
  wal_bytes numeric not null,
  wal_reset timestamptz,
  database_stats_reset timestamptz,
  blocks_read bigint not null,
  blocks_hit bigint not null,
  temp_bytes bigint not null,
  rows_inserted bigint not null,
  rows_updated bigint not null,
  rows_deleted bigint not null
);

revoke all on hyperion_ops.free_tier_usage_samples
  from public, anon, authenticated, service_role;

create or replace function hyperion_ops.capture_free_tier_usage_sample()
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  -- PostgreSQL stats are cumulative since stats_reset. A counter reset
  -- invalidates deltas until a new baseline is established.
  insert into hyperion_ops.free_tier_usage_samples as existing (
    sampled_on, measured_at, database_bytes, storage_bytes, wal_bytes,
    wal_reset, database_stats_reset, blocks_read, blocks_hit, temp_bytes,
    rows_inserted, rows_updated, rows_deleted
  )
  select
    (pg_catalog.now() at time zone 'UTC')::date,
    pg_catalog.now(),
    pg_catalog.pg_database_size(pg_catalog.current_database()),
    (select pg_catalog.coalesce(pg_catalog.sum(
      case when obj.metadata->>'size' ~ '^[0-9]+$'
        then (obj.metadata->>'size')::numeric else 0 end
    ), 0)::bigint from storage.objects as obj),
    wal.wal_bytes,
    wal.stats_reset,
    db.stats_reset,
    db.blks_read,
    db.blks_hit,
    db.temp_bytes,
    db.tup_inserted,
    db.tup_updated,
    db.tup_deleted
  from pg_catalog.pg_stat_wal as wal
  cross join pg_catalog.pg_stat_database as db
  where db.datname = pg_catalog.current_database()
  on conflict (sampled_on) do update
    set measured_at = excluded.measured_at,
        database_bytes = excluded.database_bytes,
        storage_bytes = excluded.storage_bytes,
        wal_bytes = excluded.wal_bytes,
        wal_reset = excluded.wal_reset,
        database_stats_reset = excluded.database_stats_reset,
        blocks_read = excluded.blocks_read,
        blocks_hit = excluded.blocks_hit,
        temp_bytes = excluded.temp_bytes,
        rows_inserted = excluded.rows_inserted,
        rows_updated = excluded.rows_updated,
        rows_deleted = excluded.rows_deleted
  where existing.measured_at < excluded.measured_at;

  -- Delete only telemetry generated by this migration. Customer progress,
  -- revisions, sessions, licenses, payment data and backups are untouched.
  delete from hyperion_ops.free_tier_usage_samples
  where sampled_on < (pg_catalog.now() at time zone 'UTC')::date - 45;
end;
$$;

revoke all on function hyperion_ops.capture_free_tier_usage_sample()
  from public, anon, authenticated, service_role;

-- An isolated SQL job, without HTTP networking, Secrets or Edge invocations.
-- At 00:10 UTC daily (08:10 Philippine time); pg_cron is already enabled.
select cron.schedule(
  'hyperion-free-tier-usage-daily',
  '10 0 * * *',
  'select hyperion_ops.capture_free_tier_usage_sample();'
);

-- Baseline starts on installation day so the next sample has a comparison.
select hyperion_ops.capture_free_tier_usage_sample();

commit;
